    window.RKC.centerY = (k, y, th, sy) => w.rk_center_y((k || '').charCodeAt(0), +y || 0, +th || 0, +sy || 0);
    window.RKC.axisT = (o, d, c0, ax) => w.rk_axis_t(o[0], o[1], o[2], d[0], d[1], d[2], c0[0], c0[1], c0[2], ax[0], ax[1], ax[2]);
    window.RKC.footprintDist = (px, pz, x, z, sx, sz) => w.rk_footprint_dist(px, pz, x, z, sx, sz);

    window.RKC.groundAt = (x, z, list) => {
      w.rk_reset();
      const n = list.length;
      if (!n) return 0;
      const at = scratch(n * 5 * 8);
      if (at == null) return groundAt(x, z, list);
      const box = new Float64Array(w.memory.buffer, at, n * 5);
      for (let i = 0; i < n; i++) {
        const o = list[i];
        box[i * 5] = o.x; box[i * 5 + 1] = o.z; box[i * 5 + 2] = o.sx; box[i * 5 + 3] = o.sz; box[i * 5 + 4] = o.y;
      }
      return w.rk_ground_at(x, z, at, n);
    };

    window.RKC.validate = objs => {
      w.rk_reset();
      const n = objs.length;
      if (!n) return 32;
      const at = scratch(n * 8 * 8);
      if (at == null) return validate(objs);
      const out = new Float64Array(w.memory.buffer, at, n * 8);
      for (let i = 0; i < n; i++) {
        const o = objs[i];
        out[i * 8] = o.x || 0; out[i * 8 + 1] = o.y || 0; out[i * 8 + 2] = o.z || 0;
        out[i * 8 + 3] = o.sx || 0; out[i * 8 + 4] = o.sz || 0; out[i * 8 + 5] = o.th || 0.5;
        out[i * 8 + 6] = (o.k || 'p').charCodeAt(0);
        out[i * 8 + 7] = o.k === 'p' && o.t === 'goal' ? 103 : 115;
      }
      return w.rk_validate(at, n);
    };
